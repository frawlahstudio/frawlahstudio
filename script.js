/* ==========================================================
   LAZY VIDEO LOADING (IntersectionObserver)
   Videos keep their real source in data-src until they are
   close to the viewport, so the hero/gallery never downloads
   every reel up front.
   ========================================================== */
const lazyVideoObserver = ('IntersectionObserver' in window)
    ? new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            const video = entry.target;
            if (entry.isIntersecting) {
                loadLazyVideo(video);
            } else if (video.dataset.loaded === 'true') {
                video.pause();
            }
        });
    }, { rootMargin: '300px 0px', threshold: 0.01 })
    : null;

function loadLazyVideo(video) {
    if (!video) return;

    if (video.dataset.loaded !== 'true') {
        const source = video.querySelector('source[data-src]');
        const src = video.dataset.src || (source && source.dataset.src);
        if (!src) return;

        if (source) {
            source.src = source.dataset.src;
            source.removeAttribute('data-src');
        } else {
            video.src = src;
        }

        video.preload = 'auto';
        video.dataset.loaded = 'true';
        video.muted = true;
        video.volume = 0.5;
        video.load();
    }

    video.play().catch(() => {});
}

function observeLazyVideos(root = document) {
    const videos = root.querySelectorAll('video[data-src]');
    if (lazyVideoObserver) {
        videos.forEach((video) => lazyVideoObserver.observe(video));
    } else {
        videos.forEach(loadLazyVideo);
    }
}

